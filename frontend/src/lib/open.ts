/**
 * Открывает внешнюю ссылку в системном браузере.
 *
 * В webview Tauri ни `target="_blank"`, ни `window.open` не работают: открывать
 * новые окна движку не разрешено, и ссылка молча не срабатывала. Наружу ведёт
 * только плагин opener, поэтому все внешние переходы идут через него.
 *
 * Импорт динамический — как у остальных плагинов: модуль обращается к IPC уже
 * на загрузке, и в обычном браузере статический импорт падал бы на старте.
 */
export const openExternal = async (url: string) => {
  if (!url) return;
  try {
    const { openUrl } = await import('@tauri-apps/plugin-opener');
    await openUrl(url);
  } catch (error) {
    // Молчать тут нельзя. Ссылки уже один раз «не работали» без единого следа:
    // плагину было выдано право вызвать команду, но не область видимости, и он
    // отвергал каждый URL. Со стороны это выглядело как мёртвая кнопка.
    console.error(`[opener] не удалось открыть ${url}:`, error);
  }
};
