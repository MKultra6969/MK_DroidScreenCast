/**
 * Обновление состояния «только если данные правда изменились».
 *
 * Опрос устройств и статуса записи идёт по таймеру и почти всегда возвращает
 * ровно то же самое. Но каждый ответ — новый объект, а значит новая ссылка, и
 * React перерисовывает всё дерево на ровном месте: раз в две секунды, всё
 * время работы приложения.
 *
 * Сравнение через JSON здесь уместно: полезная нагрузка — короткий список
 * устройств или плоский статус, десятки байт. Порядок ключей у ответа от
 * одного и того же бэкенда стабильный, так что ложных «изменилось» не будет.
 */
export const keepIfEqual =
  <T>(next: T) =>
  (prev: T): T => {
    try {
      return JSON.stringify(prev) === JSON.stringify(next) ? prev : next;
    } catch {
      return next;
    }
  };
